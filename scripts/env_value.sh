#!/bin/bash
# .env 에서 값을 읽는다. 기동 스크립트 둘이 공유한다.
#
# 옛 방식을 대신한다. bash 는 `KEY=값` 대입의 오른쪽에서 명령 치환을 항상 평가하므로,
# 설정 화면으로 저장할 수 있는 값에 명령 치환을 심으면 다음 기동에서 임의 명령이
# 실행되었다([INFRA-049]). 공백 하나만으로도 뒤 토큰이 명령이 되는데 Google 앱
# 비밀번호에는 공백이 들어가므로 값의 모양으로는 막을 수 없다. 원인은 값이 아니라
# 데이터 파일을 셸이 코드로 실행하는 것이라서, 읽는 방식 자체를 바꾼다.
#
# 환경 변수로 내보내지 않는다. Flask 는 app/__init__.py 의 load_dotenv() 로, Next 는
# @next/env 로 각자 .env 를 읽으므로 셸이 미리 넣어 주던 값은 이미 중복이었다.
#
# tail -1 은 중복 줄에서 나중 것이 이기는 세 파서(bash·python-dotenv·@next/env)의
# 동작에 맞춘 것이다.
#
# 읽는 대상은 **현재 작업 디렉터리의** .env 다. 두 스크립트 모두 맨 앞에서
# `cd "$PROJECT_ROOT"` 를 하므로 맞지만, restart_all.sh 는 뒤에서 `cd frontend` 와
# `cd ..` 를 오간다. 호출을 그 아래로 옮기면 조용히 빈 값이 나오므로 옮기지 않는다.
#
# 키 이름은 sed 표현식 안에 그대로 들어간다. 호출자는 리터럴 키 네 개만 넘긴다.
#
# ponytail: 따옴표·인라인 주석·후행 공백을 벗기지 않고 `export KEY=값` 도 읽지 않는다.
# 지금 이 함수가 읽는 네 키가 그 모양이 아니라서 다른 파서와 값이 같을 뿐이다. dotenv 를
# 여기서 재구현하지 않는 이유는 따옴표 안의 `#` 에서 또 갈리기 때문이다. 네 키가 그
# 모양이 되는 것이 실제 문제가 되면 그때 파이썬으로 읽어 넘긴다.
env_value() {
  # 키 이름이 sed 표현식 안으로 들어가고, env_port 에서는 ${!1} 의 이름으로도 쓰인다.
  # 둘 다 데이터를 코드로 평가하는 자리다. GNU sed 의 `s///e` 플래그는 치환 결과를 셸에
  # 넘기므로 키가 `.*/명령/e;#` 이면 그 명령이 돌고, bash 의 간접 확장은 이름 안의 배열
  # 첨자를 산술 평가하므로 `a[$(명령)]` 이면 그 명령이 돈다(bash 3.2 와 5.x 에서 실측).
  # 호출자가 리터럴 네 개만 넘기는 지금은 닿지 않지만, 이 항목이 고치는 결함이 바로 그
  # 성격이라 같은 자리를 새로 남기지 않는다.
  case $1 in
    ''|*[!A-Za-z0-9_]*)
      echo "❌ 키 이름에 쓸 수 없는 문자가 있다" >&2
      return 1
      ;;
  esac
  [ -f .env ] || return 0
  sed -n "s/^$1=//p" .env | tail -1
}

# 포트만 따로 받는다. 호출자가 `lsof -ti :$port` 처럼 인용 없이 쓰기 때문에, 값에 공백이
# 섞이면 단어 분리로 lsof 가 아무것도 찾지 못하고 stop_all.sh 가 포트를 죽이지 못한 채
# 「✅ Port freed」를 출력한다. 그 조용한 거짓 성공을 여기서 끊는다.
#
# ${!1} 은 호출자가 내보낸 같은 이름의 값이다. 옛 방식은 .env 에 키가 없을 때 아무것도
# 덮어쓰지 않아 그 값이 살아남았으므로, 우선순위를 그대로 지킨다.
#
# 지역 변수 이름을 길게 둔 이유는 ${!1} 이 이름으로 참조하기 때문이다. 흔한 이름을 쓰면
# 호출자가 그 이름을 키로 넘겼을 때 ${!1} 이 이 함수의 지역 변수 자신을 가리켜, 상속받은
# 값이 조용히 무시되고 늘 기본값으로 떨어진다.
env_port() {
  local _env_port_value
  # env_value 의 키 검사 실패를 여기서 받는다. 이 줄이 없으면 잘못된 키로도 아래 ${!1} 이
  # 평가되어 간접 확장 경로가 열린 채로 남는다.
  _env_port_value=$(env_value "$1") || return 1
  _env_port_value=${_env_port_value:-${!1:-$2}}
  case $_env_port_value in
    ''|*[!0-9]*)
      echo "❌ $1 의 값이 숫자가 아니다. .env 의 해당 줄을 확인하라" >&2
      return 1
      ;;
  esac
  printf '%s' "$_env_port_value"
}
